export function difficultyKey(difficulty: Difficulty | 'tutti'): string {
  return `difficulty${difficulty.charAt(0).toUpperCase()}${difficulty.slice(1)}`;
}

export function categoryKey(category: Category): string {
  return `cat${category.charAt(0).toUpperCase()}${category.slice(1)}`;
}

export function interpolate(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}
